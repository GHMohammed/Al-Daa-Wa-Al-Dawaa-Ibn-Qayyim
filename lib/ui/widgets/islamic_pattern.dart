import 'package:flutter/material.dart';

/// زخرفة هندسية إسلامية: وريدات اثنا عشرية في وسطها نجمة، تحيط بها بتلات
/// ونجوم خماسية، مرسومة على طريقة الأشرطة (يظهر حدّ كل شكل بين الأشرطة).
/// تُرسم بالكود فتبقى حادّة على كل الشاشات ويتغيّر لونها مع الثيم.
class IslamicPattern extends StatelessWidget {
  const IslamicPattern({
    super.key,
    required this.color,
    this.cellSize = 52,
    this.strokeWidth = 0.8,
    this.fadeToBottom = false,
  });

  final Color color;

  /// يتحكم في حجم الزخرفة — كلما صغر ازدادت الكثافة
  final double cellSize;
  final double strokeWidth;

  /// تتلاشى الزخرفة تدريجياً نحو الأسفل (لرأس الصفحة)
  final bool fadeToBottom;

  @override
  Widget build(BuildContext context) {
    final pattern = RepaintBoundary(
      child: CustomPaint(
        painter: _RosettePainter(
          color: color,
          tileWidth: cellSize * _tilesPerCell,
          strokeWidth: strokeWidth,
        ),
        size: Size.infinite,
      ),
    );
    if (!fadeToBottom) return pattern;
    return ShaderMask(
      blendMode: BlendMode.dstIn,
      shaderCallback: (rect) => const LinearGradient(
        begin: Alignment.topCenter,
        end: Alignment.bottomCenter,
        colors: [Colors.white, Colors.transparent],
        stops: [0.35, 1],
      ).createShader(rect),
      child: pattern,
    );
  }

  /// عرض الخلية المتكررة بوحدات cellSize (فيها وريدتان)
  static const double _tilesPerCell = 1.45;
}

class _RosettePainter extends CustomPainter {
  _RosettePainter({
    required this.color,
    required this.tileWidth,
    required this.strokeWidth,
  });

  final Color color;
  final double tileWidth;
  final double strokeWidth;

  /// الخلية المتكررة مستطيلة: عرضها 1 وارتفاعها هذا (بوحدة العرض)
  static const double _tileHeight = 1.37279;

  static final Path _tile = _buildTile();

  static Path _buildTile() {
    final path = Path();
    for (final p in _shapes) {
      path.moveTo(p[0], p[1]);
      for (var i = 2; i < p.length; i += 2) {
        path.lineTo(p[i], p[i + 1]);
      }
      path.close();
    }
    return path;
  }

  @override
  void paint(Canvas canvas, Size size) {
    final w = tileWidth;
    final h = tileWidth * _tileHeight;
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth / w
      ..strokeJoin = StrokeJoin.miter
      ..isAntiAlias = true;

    canvas
      ..save()
      ..clipRect(Offset.zero & size);
    // الأشكال تمتد قليلاً خارج خليتها، فنبدأ قبل الحافة بخلية
    for (var y = -h; y < size.height + h; y += h) {
      for (var x = -w; x < size.width + w; x += w) {
        canvas
          ..save()
          ..translate(x, y)
          ..scale(w)
          ..drawPath(_tile, paint)
          ..restore();
      }
    }
    canvas.restore();
  }

  @override
  bool shouldRepaint(_RosettePainter old) =>
      old.color != color ||
      old.tileWidth != tileWidth ||
      old.strokeWidth != strokeWidth;
}

